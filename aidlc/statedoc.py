"""Renders `aidlc-docs/aidlc-state.md`.

The state document is a projection of the ledger — human-readable, never a
source of truth. The recorder rewrites it after every accepted event.

Standard library only.
"""

from __future__ import annotations

from typing import List, Optional, Sequence

from . import artifacts, engine, stages
from .model import Policy, StageStatus
from .state import Snapshot

HEADING = "# AI-DLC State"

_MARKS = {
    StageStatus.PENDING: "[ ]",
    StageStatus.IN_PROGRESS: "[~]",
    StageStatus.COMPLETED: "[x]",
    StageStatus.SKIPPED: "[-]",
}


def render(snapshot: Snapshot, current: Optional[str] = None) -> str:
    lines: List[str] = [
        HEADING,
        "",
        "Generated by the AI-DLC recorder from the append-only ledger. Do not edit by hand.",
        "",
        "## Project",
        "",
        f"- **Type**: {'brownfield' if snapshot.brownfield() else 'greenfield'}",
        f"- **Languages**: {', '.join(snapshot.workspace.languages) or '(none detected)'}",
        f"- **Build systems**: "
        f"{', '.join(snapshot.workspace.build_systems) or '(none detected)'}",
        f"- **Current move**: {current or '(none)'}",
        "",
        "## Progress",
        "",
    ]
    lines.extend(_progress(snapshot))
    lines.extend(["", "## Units", ""])
    lines.extend(_units(snapshot))
    lines.extend(["", "## Extension Configuration", ""])
    lines.extend(_extensions(snapshot))
    lines.extend(["", "## Open Items", ""])
    lines.extend(_open_items(snapshot))
    lines.extend(["", "## Artifacts", ""])
    lines.extend(_artifacts(snapshot))
    return "\n".join(lines).rstrip() + "\n"


def _progress(snapshot: Snapshot) -> List[str]:
    rows: List[str] = []
    for row in engine.plan(snapshot):
        status = StageStatus(str(row["status"]))
        conditional = " (conditional)" if row["policy"] == Policy.CONDITIONAL.value else ""
        rows.append(f"- {_MARKS[status]} {row['title']}{conditional} — {status.value}")
    return rows or ["- (nothing yet)"]


def _units(snapshot: Snapshot) -> List[str]:
    units = engine.ordered_units(snapshot)
    deps = snapshot.unit_dependencies()
    if not units:
        return ["- (no units defined)"]
    lines = []
    for unit in units:
        suffix = f" (depends on: {', '.join(deps[unit])})" if deps.get(unit) else ""
        lines.append(f"- {unit}{suffix}")
    return lines


def _extensions(snapshot: Snapshot) -> List[str]:
    configured = snapshot.extensions()
    if not configured:
        return ["- (none configured — all applicable extensions are enforced)"]
    return [
        f"- {name}: {'enabled' if enabled else 'disabled'}"
        for name, enabled in sorted(configured.items())
    ]


def _open_items(snapshot: Snapshot) -> List[str]:
    lines: List[str] = []
    for event in snapshot.open_questions():
        lines.append(f"- Awaiting answers: {event.get('fields', {}).get('path')}")
    for event in snapshot.open_ambiguities():
        lines.append(f"- Unresolved ambiguity: {event.get('fields', {}).get('description')}")
    for event in snapshot.open_change_requests():
        lines.append(f"- Unconfirmed change: {event.get('fields', {}).get('request')}")
    for event in snapshot.open_human_tasks():
        lines.append(f"- HUMAN TASK: {event.get('fields', {}).get('description')}")
    return lines or ["- (none)"]


def _artifacts(snapshot: Snapshot) -> List[str]:
    lines: List[str] = []
    units: Sequence[str] = engine.ordered_units(snapshot)
    for stage in stages.STAGES:
        for artifact_id in stage.produces:
            artifact = artifacts.get(artifact_id)
            targets = units if artifact.per_unit else (None,)
            for unit in targets:
                path = artifact.resolve(unit)
                if snapshot.exists(path):
                    lines.append(f"- `{path}`")
    return sorted(set(lines)) or ["- (none yet)"]
